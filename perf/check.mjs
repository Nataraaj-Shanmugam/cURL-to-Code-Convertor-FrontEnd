#!/usr/bin/env node
/**
 * perf:check - build, measure and compare against perf/budgets.json. Exit 1 on any budget breach or if a scenario
 * could not complete. Prints the delta against perf/baseline.json (the numbers in docs/testing/performance-report.md).
 *
 *   node perf/check.mjs                  # build + bundle + web + stress
 *   node perf/check.mjs --skip-build     # reuse dist-perf
 *   node perf/check.mjs --bundle-only    # size budgets only (fast, deterministic: good for every PR)
 *   node perf/check.mjs --runs 5 --stress-runs 3 --cpu-throttle 1
 *   node perf/check.mjs --rebaseline     # after an intentional change: rewrite baseline.json + budgets.json
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib.mjs';
import { measureBundle, checkBundle } from './bundle-size.mjs';

const args = process.argv.slice(2);
const flag = (n) => args.includes(`--${n}`);
const passthrough = ['runs', 'stress-runs', 'cpu-throttle', 'observe-ms', 'quiet-ms'].flatMap((n) => (args.includes(`--${n}`) ? [`--${n}`, args[args.indexOf(`--${n}`) + 1]] : []));
const BUDGETS = join(ROOT, 'perf/budgets.json');
const BASELINE = join(ROOT, 'perf/baseline.json');

// metric -> [headroom factor over baseline, absolute floor]. Lab timings on a shared box vary +-30%, hence the headroom.
const WEB = { lcpMs: [1.6, 1500], cls: [1, 0.1], tbtMs: [2, 300], ttiMs: [1.6, 2500] };
// Floors tightened after FE-PERF-1..5 (editor rendering fixes): roughly 3x the idle-box numbers of the small scenarios,
// so a regression to per-keystroke whole-tree renders or deep-copy history fails even on a busy machine.
const STRESS = { parseToEditorMs: [1.75, 600], typingP95Ms: [2, 60], saveEditMs: [2, 80], undoMs: [2, 60], redoMs: [2, 60], reviewOpenMs: [2, 250], longestTaskMs: [2, 400], heapMB: [1.5, 25] };
const BUNDLE_HEADROOM = 1.08;

function run(cmd, cmdArgs, env = {}) {
  const r = spawnSync(cmd, cmdArgs, { cwd: ROOT, stdio: 'inherit', env: { ...process.env, ...env } });
  if (r.status !== 0) { console.error(`${cmd} ${cmdArgs.join(' ')} failed (${r.status})`); process.exit(r.status ?? 1); }
}

if (!flag('skip-build')) {
  run(join(ROOT, 'node_modules/.bin/vite'), ['build', '--config', 'perf/vite.perf.config.ts', '--mode', 'perf'], { VITE_CURL_CRAFT_API_URL: 'http://127.0.0.1:8000' });
} else if (!existsSync(join(ROOT, 'dist-perf'))) { console.error('--skip-build but dist-perf is missing'); process.exit(2); }

const bundle = measureBundle();
let results = null;
if (!flag('bundle-only')) {
  run(process.execPath, ['perf/measure.mjs', 'all', '--out', 'perf/results/check.json', ...passthrough]);
  results = JSON.parse(readFileSync(join(ROOT, 'perf/results/check.json'), 'utf8'));
}

function makeBudgets() {
  const b = { _note: 'Generated by `node perf/check.mjs --rebaseline`: baseline x headroom, never below the floor. Edit by hand only to tighten.', bundle: { totals: {}, perChunkGzipKB: {} }, web: {}, stress: {} };
  const t = bundle.totals;
  for (const k of ['jsGzipKB', 'initialJsGzipKB', 'cssGzipKB', 'largestJsChunkGzipKB']) b.bundle.totals[k] = Math.ceil(t[k] * BUNDLE_HEADROOM);
  for (const c of bundle.chunks.filter((c) => c.type === 'js' && c.gzipKB >= 5)) b.bundle.perChunkGzipKB[c.name] = Math.ceil(c.gzipKB * BUNDLE_HEADROOM);
  b.bundle.perChunkGzipKB['*'] = 10; // any other (small) chunk must stay small
  if (results) {
    for (const [page, r] of Object.entries(results.web)) {
      b.web[page] = {};
      for (const [k, [h, floor]] of Object.entries(WEB)) { const v = r.median[k]; if (v != null) b.web[page][k] = k === 'cls' ? Math.max(floor, +(v * h).toFixed(3)) : Math.ceil(Math.max(floor, v * h)); }
    }
    for (const [sc, r] of Object.entries(results.stress)) {
      if (r.median.fatal) continue;
      b.stress[sc] = {};
      for (const [k, [h, floor]] of Object.entries(STRESS)) { const v = r.median[k]; if (v != null) b.stress[sc][k] = Math.ceil(Math.max(floor, v * h)); }
    }
  }
  return b;
}

if (flag('rebaseline')) {
  if (!results) { console.error('--rebaseline needs the browser runs (drop --bundle-only)'); process.exit(2); }
  writeFileSync(BASELINE, JSON.stringify({ bundle: bundle.totals, chunks: Object.fromEntries(bundle.chunks.map((c) => [c.name, c.gzipKB])), web: Object.fromEntries(Object.entries(results.web).map(([k, v]) => [k, v.median])), stress: Object.fromEntries(Object.entries(results.stress).map(([k, v]) => [k, v.median])), meta: results.meta }, null, 2));
  writeFileSync(BUDGETS, JSON.stringify(makeBudgets(), null, 2) + '\n');
  console.log('wrote perf/baseline.json and perf/budgets.json');
  process.exit(0);
}

const budgets = JSON.parse(readFileSync(BUDGETS, 'utf8'));
const baseline = existsSync(BASELINE) ? JSON.parse(readFileSync(BASELINE, 'utf8')) : null;
const failures = checkBundle(bundle, budgets);
const rows = [];
const delta = (v, base) => (base ? `${v >= base ? '+' : ''}${Math.round(((v - base) / base) * 100)}%` : '');

if (results) {
  for (const [page, limits] of Object.entries(budgets.web ?? {})) {
    const m = results.web[page]?.median;
    if (!m) { failures.push(`web.${page}: no result`); continue; }
    for (const [k, limit] of Object.entries(limits)) {
      const v = m[k];
      if (v == null) { failures.push(`web.${page}.${k}: not measured (page never settled?)`); continue; }
      rows.push([`web.${page}.${k}`, v, limit, delta(v, baseline?.web?.[page]?.[k])]);
      if (v > limit) failures.push(`web.${page}.${k}: ${v} > budget ${limit}`);
    }
  }
  for (const [sc, limits] of Object.entries(budgets.stress ?? {})) {
    const m = results.stress[sc]?.median;
    if (!m) { failures.push(`stress.${sc}: no result`); continue; }
    if (m.fatal) failures.push(`stress.${sc}: scenario failed: ${m.fatal}`);
    for (const [name, err] of Object.entries(m.errors ?? {})) failures.push(`stress.${sc}: step "${name}" failed: ${err}`);
    for (const [k, limit] of Object.entries(limits)) {
      const v = m[k];
      if (v == null) { if (!m.fatal) failures.push(`stress.${sc}.${k}: not measured`); continue; }
      rows.push([`stress.${sc}.${k}`, v, limit, delta(v, baseline?.stress?.[sc]?.[k])]);
      if (v > limit) failures.push(`stress.${sc}.${k}: ${v} > budget ${limit}`);
    }
  }
}
console.log('\nmetric'.padEnd(36), 'value'.padStart(10), 'budget'.padStart(10), 'vs baseline'.padStart(12));
for (const [k, v, limit, d] of rows) console.log(k.padEnd(35), String(v).padStart(10), String(limit).padStart(10), d.padStart(12), v > limit ? '  <-- OVER' : '');
console.log(`\nbundle: JS ${bundle.totals.jsGzipKB} KB gzip (budget ${budgets.bundle?.totals?.jsGzipKB}), initial ${bundle.totals.initialJsGzipKB} KB (budget ${budgets.bundle?.totals?.initialJsGzipKB})`);
if (failures.length) { console.error(`\nperf:check FAILED (${failures.length}):\n  ${failures.join('\n  ')}`); process.exit(1); }
console.log('\nperf:check passed');
